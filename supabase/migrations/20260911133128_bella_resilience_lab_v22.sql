create or replace function public.bella_owner_upsert_experiment_v22(
  p_key text,
  p_label text,
  p_status text,
  p_audience_percent integer,
  p_variant_b_percent integer,
  p_overlay_a text default '',
  p_overlay_b text default '',
  p_start timestamptz default null,
  p_end timestamptz default null,
  p_reason text default null
) returns jsonb
language plpgsql security definer set search_path=''
as $$
declare
  actor uuid:=auth.uid();
  k text:=lower(trim(coalesce(p_key,'')));
  st text:=lower(trim(coalesce(p_status,'draft')));
  oldv jsonb;
  rowv jsonb;
  aud integer:=greatest(0,least(coalesce(p_audience_percent,100),100));
  vb integer:=greatest(0,least(coalesce(p_variant_b_percent,50),100));
begin
  if not public.is_bella_owner() then raise exception 'owner access required' using errcode='42501'; end if;
  if k !~ '^[a-z0-9][a-z0-9_-]{0,39}$' then raise exception 'invalid experiment key' using errcode='22023'; end if;
  if st not in ('draft','running','paused','ended') then raise exception 'invalid experiment status' using errcode='22023'; end if;
  if p_end is not null and p_start is not null and p_end <= p_start then raise exception 'experiment end must be after start' using errcode='22023'; end if;

  select to_jsonb(e) into oldv from public.bella_experiments_v22 e where e.experiment_key=k for update;
  if st='running' then
    update public.bella_experiments_v22
    set status='paused',updated_by=actor,updated_at=now(),revision=revision+1
    where kind='persona' and status='running' and experiment_key<>k;
  end if;

  insert into public.bella_experiments_v22(
    experiment_key,kind,label,status,audience_percent,variant_b_percent,overlay_a,overlay_b,starts_at,ends_at,updated_by,updated_at
  ) values (
    k,'persona',left(trim(coalesce(p_label,'')),80),st,aud,vb,left(trim(coalesce(p_overlay_a,'')),1800),left(trim(coalesce(p_overlay_b,'')),1800),p_start,p_end,actor,now()
  )
  on conflict (experiment_key) do update set
    label=excluded.label,
    status=excluded.status,
    audience_percent=excluded.audience_percent,
    variant_b_percent=excluded.variant_b_percent,
    overlay_a=excluded.overlay_a,
    overlay_b=excluded.overlay_b,
    starts_at=excluded.starts_at,
    ends_at=excluded.ends_at,
    revision=public.bella_experiments_v22.revision+1,
    updated_by=actor,
    updated_at=now()
  returning to_jsonb(bella_experiments_v22) into rowv;

  insert into public.bella_admin_audit(actor_user_id,target_user_id,action,old_value,new_value,reason)
  values(actor,actor,'v22_experiment_upsert',coalesce(oldv,'{}'::jsonb),rowv,left(trim(coalesce(p_reason,'')),240));
  return rowv;
end
$$;
revoke all on function public.bella_owner_upsert_experiment_v22(text,text,text,integer,integer,text,text,timestamptz,timestamptz,text) from public,anon;
grant execute on function public.bella_owner_upsert_experiment_v22(text,text,text,integer,integer,text,text,timestamptz,timestamptz,text) to authenticated;

create or replace function public.bella_owner_prune_events_v22(p_keep_days integer default 14)
returns integer
language plpgsql security definer set search_path=''
as $$
declare
  actor uuid:=auth.uid();
  days_to_keep integer:=greatest(1,least(coalesce(p_keep_days,14),90));
  deleted_count integer;
begin
  if not public.is_bella_owner() then raise exception 'owner access required' using errcode='42501'; end if;
  delete from public.bella_client_events_v22 where created_at < now() - make_interval(days=>days_to_keep);
  get diagnostics deleted_count = row_count;
  insert into public.bella_admin_audit(actor_user_id,target_user_id,action,old_value,new_value,reason)
  values(actor,actor,'v22_event_prune','{}'::jsonb,jsonb_build_object('deleted',deleted_count,'keep_days',days_to_keep),'Resilience Lab v22 event retention');
  return deleted_count;
end
$$;
revoke all on function public.bella_owner_prune_events_v22(integer) from public,anon;
grant execute on function public.bella_owner_prune_events_v22(integer) to authenticated;

create or replace function public.bella_owner_resilience_v22(p_event_limit integer default 40)
returns table(resilience_config jsonb, experiments jsonb, event_summary jsonb, latest_events jsonb)
language plpgsql stable security definer set search_path=''
as $$
declare
  lim integer:=greatest(1,least(coalesce(p_event_limit,40),100));
begin
  if not public.is_bella_owner() then raise exception 'owner access required' using errcode='42501'; end if;
  return query
  select
    coalesce((select to_jsonb(c) from public.bella_resilience_config_v22 c where c.id=1),'{}'::jsonb),
    coalesce((select jsonb_agg(to_jsonb(e) order by e.updated_at desc) from public.bella_experiments_v22 e),'[]'::jsonb),
    coalesce((select jsonb_agg(jsonb_build_object(
      'event_type',x.event_type,
      'module',x.module,
      'count',x.event_count,
      'last_seen',x.last_seen
    ) order by x.event_count desc,x.last_seen desc)
      from (
        select ce.event_type,ce.module,count(*)::bigint event_count,max(ce.created_at) last_seen
        from public.bella_client_events_v22 ce
        where ce.created_at > now() - interval '24 hours'
        group by ce.event_type,ce.module
        order by count(*) desc,max(ce.created_at) desc
        limit 30
      ) x),'[]'::jsonb),
    coalesce((select jsonb_agg(to_jsonb(y) order by y.created_at desc)
      from (
        select ce.id,ce.event_type,ce.module,ce.fingerprint,ce.release,ce.route,ce.status_code,ce.detail,ce.created_at
        from public.bella_client_events_v22 ce
        order by ce.created_at desc
        limit lim
      ) y),'[]'::jsonb);
end
$$;
revoke all on function public.bella_owner_resilience_v22(integer) from public,anon;
grant execute on function public.bella_owner_resilience_v22(integer) to authenticated;
