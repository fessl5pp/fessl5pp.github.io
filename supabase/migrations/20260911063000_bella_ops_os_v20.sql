create or replace function public.bella_owner_rollback_v20(p_audit_id bigint)
returns boolean
language plpgsql security definer set search_path=''
as $$
declare
  actor uuid:=auth.uid();
  a public.bella_admin_audit%rowtype;
  mid uuid;
begin
  if not public.is_bella_owner() then raise exception 'owner access required' using errcode='42501'; end if;
  select * into a from public.bella_admin_audit where id=p_audit_id for update;
  if a.id is null then raise exception 'audit row not found' using errcode='22023'; end if;
  if a.rolled_back_at is not null then raise exception 'already rolled back' using errcode='22023'; end if;

  if a.action='v20_feature_flag' then
    update public.bella_feature_flags
      set mode=coalesce(a.old_value->>'mode','on'),
          note=coalesce(a.old_value->>'note',''),
          updated_by=actor,updated_at=now()
    where feature_key=a.old_value->>'feature_key';
  elsif a.action='v20_persona_update' then
    update public.bella_persona_runtime set
      enabled=coalesce((a.old_value->>'enabled')::boolean,true),
      system_overlay=coalesce(a.old_value->>'system_overlay',''),
      brevity=coalesce(a.old_value->>'brevity','medium'),
      humor=coalesce((a.old_value->>'humor')::integer,1),
      warmth=coalesce((a.old_value->>'warmth')::integer,1),
      directness=coalesce((a.old_value->>'directness')::numeric,.35),
      dialect=coalesce((a.old_value->>'dialect')::numeric,.80),
      blocked_phrases=coalesce(a.old_value->'blocked_phrases','[]'::jsonb),
      revision=revision+1,updated_by=actor,updated_at=now()
    where id=1;
  elsif a.action in ('v20_memory_update','v20_memory_delete') then
    mid=(a.old_value->>'id')::uuid;
    update public.bella_memories set
      memory_key=coalesce(a.old_value->>'memory_key',memory_key),
      memory_text=coalesce(a.old_value->>'memory_text',memory_text),
      category=coalesce(a.old_value->>'category',category),
      source=coalesce(a.old_value->>'source',source),
      deleted_at=case when a.old_value ? 'deleted_at' and a.old_value->>'deleted_at' is not null then (a.old_value->>'deleted_at')::timestamptz else null end,
      updated_at=now()
    where id=mid;
  else
    raise exception 'rollback not supported for this action' using errcode='22023';
  end if;

  update public.bella_admin_audit set rolled_back_at=now(),rolled_back_by=actor where id=p_audit_id;
  insert into public.bella_admin_audit(actor_user_id,target_user_id,action,old_value,new_value,reason)
  values(actor,a.target_user_id,'v20_rollback',jsonb_build_object('audit_id',p_audit_id,'action',a.action),
         jsonb_build_object('restored',true),'Rollback from Ops OS v20');
  return true;
end
$$;
revoke all on function public.bella_owner_rollback_v20(bigint) from public,anon;
grant execute on function public.bella_owner_rollback_v20(bigint) to authenticated;

-- Harden the game score submission function and add season scoring.
create or replace function public.bella_submit_game_score(
  p_display_name text,
  p_game text,
  p_correct boolean,
  p_points integer,
  p_streak integer,
  p_session_complete boolean default false
) returns public.bella_game_scores
language plpgsql security definer set search_path=''
as $$
declare
  v_uid uuid:=auth.uid();
  v_name text:=left(regexp_replace(coalesce(p_display_name,'لاعب'),'\s+',' ','g'),40);
  v_points integer:=greatest(0,least(coalesce(p_points,0),100));
  v_streak integer:=greatest(0,least(coalesce(p_streak,0),1000));
  v_today date:=current_date;
  v_week date:=date_trunc('week',current_date)::date;
  v_season bigint;
  v_row public.bella_game_scores;
begin
  if v_uid is null then raise exception 'Authentication required' using errcode='42501'; end if;
  if not public.bella_is_account_active() then raise exception 'Account suspended' using errcode='42501'; end if;
  if char_length(trim(v_name))=0 then v_name:='لاعب'; end if;
  select s.id into v_season from public.bella_seasons s where s.status='active' order by s.id desc limit 1;

  insert into public.bella_game_scores as s(
    user_id,display_name,total_correct,total_answers,games_played,best_streak,xp_earned,
    daily_score,daily_date,weekly_score,week_start,season_id,season_score,updated_at
  ) values(
    v_uid,v_name,case when p_correct then 1 else 0 end,1,case when p_session_complete then 1 else 0 end,
    v_streak,v_points,v_points,v_today,v_points,v_week,v_season,v_points,now()
  )
  on conflict(user_id) do update set
    display_name=excluded.display_name,
    total_correct=s.total_correct+case when p_correct then 1 else 0 end,
    total_answers=s.total_answers+1,
    games_played=s.games_played+case when p_session_complete then 1 else 0 end,
    best_streak=greatest(s.best_streak,v_streak),
    xp_earned=s.xp_earned+v_points,
    daily_score=case when s.daily_date=v_today then s.daily_score+v_points else v_points end,
    daily_date=v_today,
    weekly_score=case when s.week_start=v_week then s.weekly_score+v_points else v_points end,
    week_start=v_week,
    season_id=v_season,
    season_score=case when s.season_id=v_season then s.season_score+v_points else v_points end,
    updated_at=now()
  returning * into v_row;
  return v_row;
end
$$;
revoke all on function public.bella_submit_game_score(text,text,boolean,integer,integer,boolean) from public,anon;
grant execute on function public.bella_submit_game_score(text,text,boolean,integer,integer,boolean) to authenticated;
