create or replace function public.bella_owner_set_feature_flag(p_key text,p_mode text,p_note text default null)
returns jsonb
language plpgsql security definer set search_path=''
as $$
declare
  actor uuid:=auth.uid();
  k text:=lower(trim(coalesce(p_key,'')));
  m text:=lower(trim(coalesce(p_mode,'')));
  oldv jsonb;
  rowv jsonb;
begin
  if not public.is_bella_owner() then raise exception 'owner access required' using errcode='42501'; end if;
  if m not in ('off','beta','on') then raise exception 'invalid mode' using errcode='22023'; end if;
  select to_jsonb(f) into oldv from public.bella_feature_flags f where f.feature_key=k for update;
  if oldv is null then raise exception 'unknown feature flag' using errcode='22023'; end if;

  update public.bella_feature_flags
  set mode=m, note=case when p_note is null then note else left(trim(p_note),300) end,
      updated_by=actor, updated_at=now()
  where feature_key=k
  returning jsonb_build_object(
    'feature_key',feature_key,'mode',mode,'label',label,'note',note,
    'updated_by',updated_by,'updated_at',updated_at
  ) into rowv;

  update public.bella_app_config set
    leaderboard_enabled=case when k='leaderboard' then m<>'off' else leaderboard_enabled end,
    content_ai_enabled=case when k='content_ai' then m<>'off' else content_ai_enabled end,
    wisdom_game_enabled=case when k='wisdom_game' then m<>'off' else wisdom_game_enabled end,
    proverb_game_enabled=case when k='proverb_game' then m<>'off' else proverb_game_enabled end,
    rumor_list_enabled=case when k='rumor_list' then m<>'off' else rumor_list_enabled end,
    box_game_enabled=case when k='box_game' then m<>'off' else box_game_enabled end,
    kuwait_quiz_enabled=case when k='kuwait_quiz' then m<>'off' else kuwait_quiz_enabled end,
    chat_ai_enabled=case when k='chat_ai' then m<>'off' else chat_ai_enabled end,
    voice_enabled=case when k='voice' then m<>'off' else voice_enabled end,
    ai_activities_enabled=case when k='ai_activities' then m<>'off' else ai_activities_enabled end,
    moments_enabled=case when k='moments' then m<>'off' else moments_enabled end,
    updated_by=actor,updated_at=now()
  where id=1;

  insert into public.bella_admin_audit(actor_user_id,target_user_id,action,old_value,new_value,reason)
  values(actor,actor,'v20_feature_flag',coalesce(oldv,'{}'::jsonb),coalesce(rowv,'{}'::jsonb),left(trim(coalesce(p_note,'')),240));
  return rowv;
end
$$;
revoke all on function public.bella_owner_set_feature_flag(text,text,text) from public,anon;
grant execute on function public.bella_owner_set_feature_flag(text,text,text) to authenticated;

create or replace function public.bella_owner_update_persona_v20(
  p_enabled boolean,
  p_system_overlay text,
  p_brevity text,
  p_humor integer,
  p_warmth integer,
  p_directness numeric,
  p_dialect numeric,
  p_blocked_phrases jsonb default '[]'::jsonb
) returns jsonb
language plpgsql security definer set search_path=''
as $$
declare
  actor uuid:=auth.uid();
  oldv jsonb;
  rowv jsonb;
  b text:=lower(trim(coalesce(p_brevity,'medium')));
begin
  if not public.is_bella_owner() then raise exception 'owner access required' using errcode='42501'; end if;
  if b not in ('short','medium','long') then raise exception 'invalid brevity' using errcode='22023'; end if;
  if jsonb_typeof(coalesce(p_blocked_phrases,'[]'::jsonb))<>'array' then raise exception 'blocked phrases must be an array' using errcode='22023'; end if;
  select to_jsonb(p) into oldv from public.bella_persona_runtime p where p.id=1 for update;
  update public.bella_persona_runtime
    set enabled=coalesce(p_enabled,true),
        system_overlay=left(trim(coalesce(p_system_overlay,'')),6000),
        brevity=b,
        humor=greatest(0,least(coalesce(p_humor,1),3)),
        warmth=greatest(0,least(coalesce(p_warmth,1),3)),
        directness=greatest(0::numeric,least(coalesce(p_directness,.35),1::numeric)),
        dialect=greatest(0::numeric,least(coalesce(p_dialect,.80),1::numeric)),
        blocked_phrases=p_blocked_phrases,
        revision=revision+1,updated_by=actor,updated_at=now()
    where id=1
    returning jsonb_build_object(
      'id',id,'enabled',enabled,'system_overlay',system_overlay,'brevity',brevity,
      'humor',humor,'warmth',warmth,'directness',directness,'dialect',dialect,
      'blocked_phrases',blocked_phrases,'revision',revision,'updated_by',updated_by,'updated_at',updated_at
    ) into rowv;
  insert into public.bella_admin_audit(actor_user_id,target_user_id,action,old_value,new_value,reason)
  values(actor,actor,'v20_persona_update',coalesce(oldv,'{}'::jsonb),coalesce(rowv,'{}'::jsonb),'Bella Persona Tuner v20');
  return rowv;
end
$$;
revoke all on function public.bella_owner_update_persona_v20(boolean,text,text,integer,integer,numeric,numeric,jsonb) from public,anon;
grant execute on function public.bella_owner_update_persona_v20(boolean,text,text,integer,integer,numeric,numeric,jsonb) to authenticated;

create or replace function public.bella_owner_user_360_v20(p_user_id uuid)
returns jsonb
language plpgsql stable security definer set search_path=''
as $$
declare outv jsonb;
begin
  if not public.is_bella_owner() then raise exception 'owner access required' using errcode='42501'; end if;
  if p_user_id is null then raise exception 'user required' using errcode='22023'; end if;
  select jsonb_build_object(
    'profile',to_jsonb(p),
    'admin',coalesce(to_jsonb(a),'{}'::jsonb),
    'games',coalesce(to_jsonb(g),'{}'::jsonb),
    'memory_count',(select count(*) from public.bella_memories m where m.user_id=p_user_id and m.deleted_at is null),
    'gift_count',(select count(*) from public.bella_user_gifts ug where ug.user_id=p_user_id),
    'badges',coalesce((select jsonb_agg(jsonb_build_object('badge_key',ub.badge_key,'title',b.title,'icon',b.icon,'awarded_at',ub.awarded_at,'note',ub.note) order by ub.awarded_at desc)
                       from public.bella_user_badges ub join public.bella_badges b on b.badge_key=ub.badge_key where ub.user_id=p_user_id),'[]'::jsonb)
  ) into outv
  from public.bella_profiles p
  left join public.bella_account_admin a on a.user_id=p.user_id
  left join public.bella_game_scores g on g.user_id=p.user_id
  where p.user_id=p_user_id;
  if outv is null then raise exception 'user not found' using errcode='22023'; end if;
  return outv;
end
$$;
revoke all on function public.bella_owner_user_360_v20(uuid) from public,anon;
grant execute on function public.bella_owner_user_360_v20(uuid) to authenticated;

