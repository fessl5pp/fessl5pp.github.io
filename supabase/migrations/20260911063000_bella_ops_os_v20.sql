create or replace function public.bella_season_leaderboard_v20(p_limit integer default 20)
returns table(user_id uuid,display_name text,season_score bigint,place bigint)
language sql stable security definer set search_path=''
as $$
  with current_s as (
    select s.id from public.bella_seasons s where s.status='active' order by s.id desc limit 1
  ), ranked as (
    select g.user_id,g.display_name,g.season_score,
           row_number() over(order by g.season_score desc,g.updated_at asc,g.user_id) place
    from public.bella_game_scores g
    left join public.bella_account_admin a on a.user_id=g.user_id
    where g.season_id=(select id from current_s)
      and g.season_score>0
      and coalesce(a.leaderboard_blocked,false)=false
  )
  select r.user_id,r.display_name,r.season_score,r.place
  from ranked r order by r.place
  limit greatest(1,least(coalesce(p_limit,20),100));
$$;
