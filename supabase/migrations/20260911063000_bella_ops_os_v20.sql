create or replace function public.bella_owner_close_season_v20(p_next_name text default null)
returns jsonb
language plpgsql security definer set search_path=''
as $$
declare
  actor uuid:=auth.uid();
  sid bigint;
  sname text;
  nextid bigint;
  nextname text;
  winner record;
  cnt integer:=0;
begin
  if not public.is_bella_owner() then raise exception 'owner access required' using errcode='42501'; end if;
  select s.id,s.name into sid,sname from public.bella_seasons s where s.status='active' order by s.id desc limit 1 for update;
  if sid is null then raise exception 'no active season' using errcode='22023'; end if;

  delete from public.bella_season_winners where season_id=sid;
  for winner in
    select g.user_id,g.display_name,g.season_score,
           row_number() over(order by g.season_score desc,g.updated_at asc,g.user_id) place
    from public.bella_game_scores g
    left join public.bella_account_admin a on a.user_id=g.user_id
    where g.season_id=sid and g.season_score>0 and coalesce(a.leaderboard_blocked,false)=false
    order by g.season_score desc,g.updated_at asc,g.user_id
    limit 3
  loop
    insert into public.bella_season_winners(season_id,user_id,place,score,display_name)
    values(sid,winner.user_id,winner.place,winner.season_score,winner.display_name);
    if winner.place=1 then
      insert into public.bella_user_badges(user_id,badge_key,season_id,awarded_by,note)
      values(winner.user_id,'alnawkhadha',sid,actor,'بطل '||sname);
    elsif winner.place=2 then
      insert into public.bella_user_badges(user_id,badge_key,season_id,awarded_by,note)
      values(winner.user_id,'alsirdal',sid,actor,'وصيف '||sname);
    elsif winner.place=3 then
      insert into public.bella_user_badges(user_id,badge_key,season_id,awarded_by,note)
      values(winner.user_id,'raei_alfazaa',sid,actor,'المركز الثالث في '||sname);
    end if;
    cnt:=cnt+1;
  end loop;

  update public.bella_seasons set status='closed',ends_at=coalesce(ends_at,now()),closed_at=now() where id=sid;
  nextname:=nullif(left(trim(coalesce(p_next_name,'')),100),'');
  if nextname is null then nextname:='الموسم '||(sid+1)::text; end if;
  insert into public.bella_seasons(name,status,created_by) values(nextname,'active',actor) returning id into nextid;
  update public.bella_game_scores set season_id=nextid,season_score=0,updated_at=now();

  insert into public.bella_admin_audit(actor_user_id,target_user_id,action,old_value,new_value,reason)
  values(actor,actor,'v20_close_season',jsonb_build_object('season_id',sid,'name',sname),
         jsonb_build_object('next_season_id',nextid,'next_name',nextname,'winners',cnt),'Season rollover');

  return jsonb_build_object('closed_season_id',sid,'closed_name',sname,'next_season_id',nextid,'next_name',nextname,'winners_saved',cnt);
end
$$;
