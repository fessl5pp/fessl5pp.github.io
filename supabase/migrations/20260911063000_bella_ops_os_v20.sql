create or replace function public.bella_public_ops_v20()
returns table(
  feature_flags jsonb,
  persona_style jsonb,
  current_season jsonb
)
language sql stable security definer set search_path=''
as $$
  with me as (
    select public.is_bella_owner() as is_owner
  ),
  flags as (
    select coalesce(jsonb_object_agg(
      f.feature_key,
      jsonb_build_object(
        'mode', f.mode,
        'effective', case when f.mode='on' then true when f.mode='beta' then (select is_owner from me) else false end,
        'label', f.label,
        'note', f.note
      )
    ), '{}'::jsonb) value
    from public.bella_feature_flags f
  ),
  persona as (
    select jsonb_build_object(
      'enabled',p.enabled,'brevity',p.brevity,'humor',p.humor,'warmth',p.warmth,
      'directness',p.directness,'dialect',p.dialect,'revision',p.revision,'updated_at',p.updated_at
    ) value
    from public.bella_persona_runtime p where p.id=1
  ),
  season as (
    select jsonb_build_object(
      'id',s.id,'name',s.name,'starts_at',s.starts_at,'ends_at',s.ends_at,'status',s.status
    ) value
    from public.bella_seasons s where s.status='active' order by s.id desc limit 1
  )
  select (select value from flags),
         coalesce((select value from persona),'{}'::jsonb),
         coalesce((select value from season),'{}'::jsonb);
$$;
revoke all on function public.bella_public_ops_v20() from public;
grant execute on function public.bella_public_ops_v20() to anon, authenticated;

