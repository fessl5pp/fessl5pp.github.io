create or replace function public.bella_owner_global_drop_v20(
  p_xp integer default 0,
  p_badge_key text default null,
  p_label text default 'هدية جماعية من بيلا 🎁',
  p_message text default null,
  p_reason text default null
) returns jsonb
language plpgsql security definer set search_path=''
as $$
declare
  actor uuid:=auth.uid();
  amount integer:=greatest(0,least(coalesce(p_xp,0),5000));
  badge text:=nullif(trim(coalesce(p_badge_key,'')),'');
  affected integer:=0;
  gifted integer:=0;
begin
  if not public.is_bella_owner() then raise exception 'owner access required' using errcode='42501'; end if;
  if amount=0 and badge is null and trim(coalesce(p_message,''))='' then raise exception 'empty drop' using errcode='22023'; end if;
  if badge is not null and not exists(select 1 from public.bella_badges b where b.badge_key=badge and b.active) then raise exception 'badge not found' using errcode='22023'; end if;

  if amount>0 then
    update public.bella_profiles p
      set xp=least(1000000,p.xp+amount),
          level=greatest(1,floor(least(1000000,p.xp+amount)/100.0)::integer+1),
          updated_at=now()
    where not exists(
      select 1 from public.bella_account_admin a
      where a.user_id=p.user_id and a.account_status='suspended'
        and not (a.suspension_type='temporary' and a.suspended_until is not null and a.suspended_until<=now())
    );
    get diagnostics affected=row_count;
  end if;

  if trim(coalesce(p_message,''))<>'' or amount>0 then
    insert into public.bella_user_gifts(user_id,gift_type,label,message,xp_amount,created_by)
    select p.user_id,case when amount>0 then 'bonus' else 'gift' end,
           left(trim(coalesce(p_label,'هدية جماعية من بيلا 🎁')),120),
           left(trim(coalesce(p_message,'')),500),amount,actor
    from public.bella_profiles p
    where not exists(
      select 1 from public.bella_account_admin a
      where a.user_id=p.user_id and a.account_status='suspended'
        and not (a.suspension_type='temporary' and a.suspended_until is not null and a.suspended_until<=now())
    );
    get diagnostics gifted=row_count;
    update public.bella_profiles p
      set gifts=p.gifts+1,updated_at=now()
    where not exists(
      select 1 from public.bella_account_admin a
      where a.user_id=p.user_id and a.account_status='suspended'
        and not (a.suspension_type='temporary' and a.suspended_until is not null and a.suspended_until<=now())
    );
  end if;

  if badge is not null then
    insert into public.bella_user_badges(user_id,badge_key,season_id,awarded_by,note)
    select p.user_id,badge,(select s.id from public.bella_seasons s where s.status='active' order by s.id desc limit 1),
           actor,left(trim(coalesce(p_reason,'Global Drop')),240)
    from public.bella_profiles p
    where not exists(
      select 1 from public.bella_account_admin a
      where a.user_id=p.user_id and a.account_status='suspended'
        and not (a.suspension_type='temporary' and a.suspended_until is not null and a.suspended_until<=now())
    );
  end if;

  insert into public.bella_admin_audit(actor_user_id,target_user_id,action,old_value,new_value,reason)
  values(actor,actor,'v20_global_drop','{}'::jsonb,
         jsonb_build_object('xp',amount,'badge_key',badge,'profiles',affected,'gifts',gifted),
         left(trim(coalesce(p_reason,'')),240));
  return jsonb_build_object('profiles_updated',affected,'gifts_sent',gifted,'xp_each',amount,'badge_key',badge);
end
$$;
revoke all on function public.bella_owner_global_drop_v20(integer,text,text,text,text) from public,anon;
grant execute on function public.bella_owner_global_drop_v20(integer,text,text,text,text) to authenticated;

