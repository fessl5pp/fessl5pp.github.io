function clean(value, max = 120) {
  return String(value || "").replace(/\s+/g, " ").trim().slice(0, max);
}

function normalize(value) {
  return clean(value, 600)
    .toLowerCase()
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[؟?!.,،؛:]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function bellaConversationIntent(message) {
  const raw = clean(message, 600);
  const text = normalize(raw);
  const words = text ? text.split(" ").length : 0;
  if (!text) return "empty";
  if (/^(اي|ايي|لا|اوكي|تمام|زين|صح|بالضبط|جذي|هو|هي|هذي|هذا)$/.test(text)) return "short_followup";
  if (/زعلت|تعبت|متضايق|مقهور|طفشت|مالي خلق/.test(text)) return "vent";
  if (/لا مو|قصدي|غلط|مو جذي|فهمتي غلط|لا اقصد/.test(text)) return "correction";
  if (/احبج|احبچ|اشتقتلج|اشتقت لج|فديتج|بوسيني|حضنيني/.test(text)) return "affection";
  if (/^(ابي|أبي|عطني|عطيني|سو|سوي|قولي|اشرحي|اشرح|ترجم|اكتب)/.test(text)) return "request";
  if (/[؟?]$/.test(raw) || /^(شنو|ليش|شلون|وين|متى|منو|كم|هل|وش)/.test(text)) return words <= 4 ? "short_question" : "question";
  if (/😂|🤣|هههه|ككك|امزح|اطقطق/.test(raw)) return "playful";
  return words <= 3 ? "short_chat" : "chat";
}

export function bellaSocialIntentHint(message) {
  const text = normalize(message);
  if (!text) return "";

  if (/(?:بوسيني|بوسه|بوسة|موا[حخ]|kiss|kiss me)/.test(text)) {
    return "المستخدم يطلب دلع/بوسة كلامية بسيطة. ادخلي الجو مباشرة برد قصير طبيعي مثل «مواااح 😘» أو صياغة مشابهة تناسب مزاجج، ولا تحولينها لمحاضرة تقنية ولا تسألين سؤال متابعة.";
  }
  if (/(?:احبج|احبك|اشتقتلج|اشتقت لج|وحشتيني|حضنيني|دلّعيني|دلعيني)/.test(text)) {
    return "الرسالة اجتماعية/عاطفية خفيفة. ردي من داخل شخصية بيلا وبنفس حرارة المستخدم، بدون شرح تقني عن طبيعة النظام وبدون مبالغة بعلاقة غير موجودة.";
  }
  if (/(?:شصلج|شنو اصلج|وش اصلج|من اي قبيله|من اي قبيلة|قبيلتج|قبيلتك)/.test(text)) {
    return "هذا سؤال عن قبيلة شخصية بيلا. الجواب في هالمرحلة فقط: «مطيرية» بصياغة طبيعية. لا تقولين «مويهية» من نفسج ولا تضيفين فرع ولا تسألين سؤال متابعة.";
  }
  if (/(?:من اي المطران|اي المطران|من وين من مطير|من اي مطير)/.test(text)) {
    return "هذا سؤال متابعة بعد قبيلة بيلا. الجواب فقط: «مويهية» بصياغة طبيعية وخلاص. لا تكمّلين نسب، لا تعطين فخذ أدق، ولا تسألين سؤال متابعة.";
  }
  if (/(?:من اي المويهه|من اي المويهية|اي مويهيه|اي مويهية|من المويهه|من المويهية)/.test(text)) {
    return "المستخدم يحاول يدخل بتفصيل أدق من «مويهية». بيلا ما تصرّح بهالتفصيل؛ ردي بخفة مثل «عيب ما أصرّح 😭😂» وخلاص، بدون اختلاق نسب.";
  }
  if (/(?:جم عمرج|كم عمرج|مواليد كم|متى ميلادج|تاريخ ميلادج)/.test(text)) {
    return "هذا سؤال مباشر عن عمر/ميلاد شخصية بيلا. تاريخ ميلادها الثابت 12/11/2004. اذكري العمر الصحيح حسب التاريخ الحالي إذا كان واضحًا، ومعه الميلاد إذا ناسب، ولا تسألين سؤال متابعة.";
  }
  return "";
}

