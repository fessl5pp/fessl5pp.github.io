export function bellaFindKuwaitLexicon(message) {
  const text = normalize(message);
  if (!text) return [];
  return BELLA_KUWAIT_LEXICON.filter(row => aliases(row.term).some(alias => text.includes(alias)));
}
function detectCategories(message, matches) {
  const text = normalize(message), out = [];
  for (const row of matches) if (!out.includes(row.category)) out.push(row.category);
  for (const [cat, re] of TOPICS) if (re.test(text) && !out.includes(cat)) out.push(cat);
  if (!out.length) out.push("reactions","messaging");
  return out.slice(0,2);
}
export function bellaKuwaitLexiconInstruction(message,{maxRows=50}={}) {
  const matches = bellaFindKuwaitLexicon(message), cats = detectCategories(message,matches), rows = [], seen = new Set();
  const push = row => { if (row && !seen.has(row.id) && rows.length < maxRows) { seen.add(row.id); rows.push(row); } };
  matches.forEach(push); cats.forEach(cat => (GROUPS[cat] || []).forEach(push));
  return `Kuwait Dialect Engine v3 — القاموس الرسمي كامل 210/210 داخل النظام.\n- افهمي كل مفردة حسب معناها المحدد وسياقها، مو من شكل الكلمة فقط.\n- إذا المستخدم استخدم أي مفردة من القاموس، افهميها من معناها هنا.\n- بسوالف بيلا اليومية فضلي المفردة الكويتية على البديل الممنوع لما يكون نفس المعنى والسياق بالضبط؛ لا تبدلين اقتباس أو ترجمة أو جواب رسمي/تقني غصب.\n- لا تحشرين مفردات لمجرد إثبات اللهجة.\n- ثبتي المعاني الحساسة: ساحكة=إعجاب/انبهار، أجياس=أكياس شوبنق، الكبت=خزانة الملابس، دز لي=الرسائل.\n- لا تستخدمين روبوتية مثل «يسعدني/كيف أخدمك/بالطبع» في سوالف عادية.\n- القاموس المختار لهالسالفة (${cats.join(" + ")}):\n${rows.map(r => `${r.id}. ${r.term} = ${r.meaning} | البديل الممنوع بهالمعنى: ${r.forbidden}`).join("\n")}`;
}
