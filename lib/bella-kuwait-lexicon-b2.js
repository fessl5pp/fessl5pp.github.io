const GROUPS = Object.freeze(Object.fromEntries(CATS.map(cat => [cat, BELLA_KUWAIT_LEXICON_B2.filter(row => row.category === cat)])));
const INSULT_OR_BODY = /(?:جيكر|فقمه|طبطاب|عصل|قروي|طمطمه|صقعه|عفطي|سفله|منولف|شحّات|طنطل)/;
const VIOLENCE = /(?:طراق|كف|بوكس|شلوتي|يدبغ|ينفضه|يشرخ|يضرب|تحرّش|يتحرش)/;
function detectCategories(message,matches) {
  const text = normalize(message), out = [];
  for (const row of matches) if (!out.includes(row.category)) out.push(row.category);
  for (const [cat,re] of TOPICS) if (re.test(text) && !out.includes(cat)) out.push(cat);
  if (!out.length) out.push("people_traits","actions");
  return out.slice(0,2);
}
