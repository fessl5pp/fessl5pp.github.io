function normalize(value) {
  return String(value || "").toLowerCase().replace(/[أإآ]/g,"ا").replace(/ى/g,"ي").replace(/ة/g,"ه").replace(/[ًٌٍَُِّْـ]/g,"").replace(/[^\p{L}\p{N}]+/gu," ").replace(/\s+/g," ").trim();
}
function aliases(term) {
  const raw = String(term || "");
  const paren = [...raw.matchAll(/\(([^)]+)\)/g)].map(m => m[1]);
  const base = raw.replace(/\([^)]*\)/g," ");
  const parts = [...raw.split(/\s*\/\s*/), base, ...paren];
  return [...new Set(parts.map(normalize).filter(Boolean))];
}
export function bellaFindKuwaitLexiconB2(message) {
  const text = normalize(message);
  if (!text) return [];
  return BELLA_KUWAIT_LEXICON_B2.filter(row => aliases(row.term).some(alias => text.includes(alias)));
}
